function api({qrCode='<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg xmlns="http://www.w3.org/2000/svg" width="220" height="220"></svg>',factors=[],verification=session('aal2',[factor]),activateError=false,paused=false,pending=false}={}){
 const calls=[];
 return {calls,fetch:async(path,options={})=>{
  calls.push({path,options});
  if(path.includes('/rpc/touch_store_admin_session')){const t=Date.now();return response({server_now:new Date(t).toISOString(),expires_at:new Date(t+43200000).toISOString(),idle_expires_at:new Date(t+1800000).toISOString()})}
  if(path.includes('/rpc/store_admin_security_status'))return response({paused,pending,access_role:pending?null:'owner'});
  if(path.includes('/store_admins'))return response(pending?[]:[{user_id:'owner'}]);
  if(path.endsWith('/auth/v1/user'))return response(user(factors));
  if(path.endsWith('/challenge'))return response({id:'challenge'});
  if(path.endsWith('/verify')){factors=[factor];return response(verification)}
  if(path.includes('/rpc/enforce_store_mfa')){if(!activateError)paused=false;return response(activateError?{message:'activation unavailable'}:true,activateError?503:200);}
  if(path.endsWith('/auth/v1/factors'))return response({id:'new-factor',type:'totp',totp:{secret:'SYNTHETIC-SECRET',qr_code:qrCode}});
  return response([]);
 }};
}
